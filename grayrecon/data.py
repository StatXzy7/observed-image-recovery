"""Fixed-seed synthetic grayscale images, masks, blur kernels and data."""

from __future__ import annotations

import numpy as np


def synthetic_image(shape=(16, 16), seed: int = 7) -> np.ndarray:
    """Deterministic smooth synthetic image in [0, 1] made of Gaussian blobs."""
    h, w = shape
    rng = np.random.default_rng(seed)
    yy, xx = np.mgrid[0:h, 0:w].astype(np.float64)
    image = np.full(shape, 0.25, dtype=np.float64)
    n_blobs = 3 + int(rng.integers(0, 3))
    for _ in range(n_blobs):
        cy = float(rng.uniform(0.2 * h, 0.8 * h))
        cx = float(rng.uniform(0.2 * w, 0.8 * w))
        sigma = float(rng.uniform(0.10, 0.22) * max(h, w))
        amp = float(rng.uniform(0.15, 0.4))
        image += amp * np.exp(-((yy - cy) ** 2 + (xx - cx) ** 2)
                              / (2.0 * sigma ** 2))
    image -= image.min()
    image /= image.max()
    return image


def random_mask(shape, missing_fraction: float = 0.3,
                seed: int = 11) -> np.ndarray:
    """Boolean mask; ``True`` marks observed pixels."""
    if not (0.0 <= missing_fraction <= 1.0):
        raise ValueError("missing_fraction must lie in [0, 1]")
    rng = np.random.default_rng(seed)
    n = int(shape[0]) * int(shape[1])
    n_missing = int(round(missing_fraction * n))
    order = rng.permutation(n)
    mask = np.ones(n, dtype=bool)
    mask[order[:n_missing]] = False
    return mask.reshape(shape)


def box_kernel(size: int = 3) -> np.ndarray:
    """Uniform odd-sized box blur kernel."""
    if size % 2 == 0 or size < 1:
        raise ValueError("kernel size must be a positive odd integer")
    return np.ones((size, size), dtype=np.float64) / (size * size)


def make_problem(shape=(16, 16), missing_fraction: float = 0.3,
                 kernel_size: int = 3, noise_sigma: float = 0.0,
                 seed: int = 7, mask_seed: int = 11):
    """Build a complete synthetic problem: truth, mask, kernel and observation.

    The observation is generated by the same forward operator used in the
    solver, optionally with fixed-seed Gaussian measurement noise.
    """
    from .operators import MaskedBlur, normalize_kernel

    truth = synthetic_image(shape, seed=seed)
    mask = random_mask(shape, missing_fraction, seed=mask_seed)
    kernel = normalize_kernel(box_kernel(kernel_size))
    operator = MaskedBlur(shape, kernel, mask.astype(np.float64))
    observation = operator(truth)
    if noise_sigma > 0.0:
        rng = np.random.default_rng(seed + 1000)
        observation = observation + noise_sigma * rng.standard_normal(shape)
        observation = operator.mask * observation
    return {
        "truth": truth,
        "mask": mask,
        "kernel": kernel,
        "operator": operator,
        "observation": observation,
    }
