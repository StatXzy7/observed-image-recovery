"""Fixed-seed synthetic grayscale images and bundled inverse problems.

Images are returned on the internal scale [-1, 1]. The patterns are smooth,
low-frequency fields that a small tanh generator can represent well.
"""

from __future__ import annotations

from dataclasses import dataclass

import numpy as np

from .config import GeneratorConfig
from .generator import generator_forward, random_generator_config
from .operators import forward_observation, gaussian_kernel, random_mask


@dataclass
class Problem:
    true_image: np.ndarray
    observation: np.ndarray
    kernel: np.ndarray
    mask: np.ndarray
    generator: GeneratorConfig


def synthetic_image(
    height: int = 12, width: int = 12, seed: int = 0
) -> np.ndarray:
    """Deterministic smooth synthetic image on the scale [-1, 1]."""
    if height < 2 or width < 2:
        raise ValueError("image dimensions must be at least 2")
    yy, xx = np.meshgrid(
        np.linspace(0.0, 2.0 * np.pi, width, dtype=np.float64),
        np.linspace(0.0, 2.0 * np.pi, height, dtype=np.float64),
        indexing="ij",
    )
    rng = np.random.default_rng(seed)
    a1, a2 = rng.uniform(0.5, 1.0, size=2)
    p1, p2 = rng.uniform(0.0, 2.0 * np.pi, size=2)
    pattern = (
        a1 * np.sin(1.0 * xx + p1)
        + a2 * np.cos(1.0 * yy + p2)
        + 0.35 * np.sin(xx + yy)
    )
    pattern /= max(1.0, float(np.max(np.abs(pattern))))
    return pattern.astype(np.float64)


def _latent_for_image(
    image: np.ndarray, config: GeneratorConfig, seed: int, max_iter: int = 3000
) -> np.ndarray:
    """Fit a latent code so the generator closely reproduces ``image``.

    Plain gradient descent with a fixed step; used only to build an exactly
    model-consistent sample problem. The fitted code is returned.
    """
    target = image.ravel()
    rng = np.random.default_rng(seed)
    z = 0.2 * rng.standard_normal(config.latent_dim)
    step = 0.1
    for _ in range(max_iter):
        img, hidden, pre_output = generator_forward(z, config)
        g = img.ravel()
        d_out = (g - target) * (1.0 - np.tanh(pre_output) ** 2)
        d_hidden = d_out @ config.w2.T * (1.0 - hidden**2)
        grad = d_hidden @ config.w1.T
        z -= step * grad
    return z


def make_problem(
    height: int = 12,
    width: int = 12,
    missing_fraction: float = 0.3,
    kernel_size: int = 3,
    kernel_sigma: float = 1.0,
    seed: int = 0,
) -> Problem:
    """Create a random-mask deblurring problem with a fresh generator."""
    image = synthetic_image(height, width, seed=seed)
    kernel = gaussian_kernel(kernel_size, kernel_sigma)
    mask = random_mask((height, width), missing_fraction, seed=seed + 101)
    generator = random_generator_config((height, width), seed=seed + 202)
    observation = forward_observation(image, kernel, mask)
    return Problem(
        true_image=image,
        observation=observation,
        kernel=kernel,
        mask=mask,
        generator=generator,
    )


def make_solvable_problem(
    height: int = 10,
    width: int = 10,
    missing_fraction: float = 0.25,
    kernel_size: int = 3,
    latent_dim: int = 12,
    hidden_dim: int = 40,
    seed: int = 42,
) -> tuple[Problem, np.ndarray]:
    """Build a model-consistent problem.

    The ground truth is generated by the configured network from a known
    latent code, so alternating optimisation has a near-exact solution.
    Returns the problem and the ground-truth latent code.
    """
    config = random_generator_config(
        (height, width),
        latent_dim=latent_dim,
        hidden_dim=hidden_dim,
        seed=seed + 1,
    )
    rng = np.random.default_rng(seed + 2)
    z_true = rng.standard_normal(latent_dim) * 0.8
    image, _, _ = generator_forward(z_true, config)
    kernel = gaussian_kernel(kernel_size, 1.0)
    mask = random_mask((height, width), missing_fraction, seed=seed + 3)
    observation = forward_observation(image, kernel, mask)
    problem = Problem(
        true_image=image,
        observation=observation,
        kernel=kernel,
        mask=mask,
        generator=config,
    )
    return problem, z_true
